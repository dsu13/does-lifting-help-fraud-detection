_CONE_COUNTS = [("Cones", "n_cone_cells", "frac_nodes_with_cone"),
                ("FutCones", "n_future_cone_cells", "frac_nodes_with_future_cone")]
_SAME_RUN = ("window", "window_frac", "epochs", "temporal_split")


def table_temporal_variants() -> None:
    """Temporal variants (cones, time-aware gate) at full labels.

    Each temporal_variants*.json is paired by seed with the arms of temporal_crossover.json:
    same graph, window, splits and seeds, and every arm reseeds itself."""
    rows, macros = [], []
    for ds, sfx, label in _VARIANT_DATASETS:
        main = _load(_result(ds, "temporal_crossover.json"))
        cm = main["_config"]
        pool = {k: v for k, v in main.items() if not k.startswith("_")}
        counts: Dict[str, object] = {}
        for path in _result_glob(ds, "temporal_variants*.json"):
            var = _load(path)
            cv = var["_config"]
            diff = [k for k in _SAME_RUN if cv.get(k) != cm.get(k)]
            if diff:
                log.warning("%s: %s differ from the main run; skipped", path.name, diff)
                continue
            if cv.get("seeds") != cm.get("seeds"):
                log.warning("%s (%s): seeds %s vs main %s; paired on the common seeds",
                            path.name, ds, cv.get("seeds"), cm.get("seeds"))
            pool.update({k: v for k, v in var.items() if not k.startswith("_")})
            counts.update(cv)
        # arm D at every swept window against the uncut pool; the other windows get
        # their own rows after the main-window one
        split_rows = []
        if _FULL in pool.get("D_static_cells", {}):
            for frac, run in _window_runs(ds).items():
                if frac != round(float(cm["window_frac"]), 6):
                    r = _pair_test(run["D_temporal_cells"][_FULL], pool["D_static_cells"][_FULL])
                    split_rows.append((frac, f" & D at $\\omega{{=}}{100 * frac:g}\\%$ "
                                             f"$-$ D on the uncut pool & {_fmt_test(r)} \\\\"))
        first = True
        for name, lhs, rhs, text in _VARIANT_TESTS:
            left, right = pool.get(lhs, {}), pool.get(rhs, {})
            if _FULL not in left or _FULL not in right:
                continue
            r = _pair_test(left[_FULL], right[_FULL])
            if name in _VARIANT_MACROS:
                macros += _macros(f"{name}Full{sfx}", r)
            rows.append(f"{label if first else ''} & {text} & {_fmt_test(r)} \\\\")
            first = False
            if name == "Split":
                rows += [row for _, row in sorted(split_rows)]
        for name, n_key, frac_key in _CONE_COUNTS:
            if n_key in counts:
                macros += [f"\\newcommand{{\\n{name}{sfx}}}{{{counts[n_key]:,}}}".replace(",", "{,}"),
                           f"\\newcommand{{\\cover{name}{sfx}}}{{{100 * counts[frac_key]:.0f}}}"]
        if not first:
            rows.append("\\midrule")
    if rows and rows[-1] == "\\midrule":
        rows.pop()
    body = ("% auto-generated -- temporal variants at full labels, paired over seeds\n"
            "\\begin{tabular}{llc}\n\\toprule\n"
            "Dataset & Comparison & $\\Delta$AP [95\\% CI], $p$ \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    _write("tab_temporal_variants.tex", body)
    _write("crossover_stats_variants.tex", "\n".join(macros) + "\n")


