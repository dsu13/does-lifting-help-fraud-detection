def _fmt_test(r: Dict[str, float]) -> str:
    """Table cell like '+1.2 [+0.3, +2.1], p=0.013', in AP points."""
    if r["diff"] != r["diff"]:
        return "--"
    ci = ("" if r["lo"] != r["lo"]
          else f"\\,[{r['lo']*100:+.1f}, {r['hi']*100:+.1f}]")
    return f"${_num(r['diff'] * 100, '+.1f')}{ci}$, ${_fmt_p(r['p'])}$"


def table_elliptic_redesign() -> None:
    """Arm D at full labels on the cross-step pool vs the same-step control and the static pool.

    The pools share graph, splits and seeds, so pairing by seed across files is valid."""
    rows = []
    for base, label in _REDESIGN:
        runs = {"static": _load(_result(base, "temporal_crossover.json"))}
        for pool in _POOLS:
            runs[pool] = _load(_result(f"{base}_{pool}", "temporal_crossover.json"))
        for lhs, rhs, text in _REDESIGN_PAIRS:
            if runs[rhs]["_config"]["temporal_split"] != runs[lhs]["_config"]["temporal_split"]:
                log.warning("redesign %s: %s and %s used different split protocols; skipped",
                            base, lhs, rhs)
                continue
            r = _pair_test(runs[lhs]["D_temporal_cells"][_FULL],
                           runs[rhs]["D_temporal_cells"][_FULL])
            rows.append(f"{label} & {text} & {_fmt_test(r)} \\\\")
    body = ("% auto-generated -- Elliptic redesign: arm D across candidate pools, full labels\n"
            "\\begin{tabular}{llc}\n\\toprule\n"
            "Graph & Comparison & $\\Delta$AP [95\\% CI], $p$ \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    _write("tab_elliptic_redesign.tex", body)


def _window_runs(ds: str) -> Dict[float, dict]:
    """Crossover runs of a dataset by omega share: temporal_crossover.json first, then the
    temporal_crossover_w*.json of the window sweep."""
    runs: Dict[float, dict] = {}
    for path in [_result(ds, "temporal_crossover.json")] + _result_glob(ds, "temporal_crossover_w*.json"):
        res = _load(path)
        runs.setdefault(round(float(res["_config"]["window_frac"]), 6), res)
    return runs


def table_window_sweep() -> None:
    """D-B at full labels for each crossover run, one row per dataset and omega."""
    rows = []
    for ds, label in _SWEEP_DATASETS:
        runs = _window_runs(ds)
        for frac in sorted(runs):
            res = runs[frac]
            c = res["_config"]
            r = _pair_test(res["D_temporal_cells"][_FULL], res["B_temporal_cols"][_FULL])
            rows.append(
                f"{label} & {100*float(frac):g}\\% & {float(c['window']):.4g} & "
                f"{100 * c['frac_cells_split']:.0f} & {100 * c['frac_cells_spanning_time']:.0f} & "
                f"{'yes' if c['temporal_arms_degenerate'] else 'no'} & {_fmt_test(r)} \\\\")
    body = ("% auto-generated -- window sweep: D-B at full labels per dataset and omega\n"
            "\\begin{tabular}{lcccccc}\n\\toprule\n"
            "Dataset & $\\omega$/span & $\\omega$ & split (\\%) & span time (\\%) & "
            "degenerate & D$-$B [95\\% CI], $p$ \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    _write("tab_window_sweep.tex", body)


