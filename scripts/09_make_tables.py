def _fmt_gap_p(r: Dict[str, float]) -> str:
    """Table cell like '+1.2 (0.013)': gap in AP points, two-sided p in small type."""
    if r["diff"] != r["diff"]:
        return "--"
    p = r["p"]
    s = "--" if p != p else _p_text(p)
    ps = f"${s}$" if s.startswith("<") else s
    return f"${_num(r['diff'] * 100, '+.1f')}$\\,{{\\scriptsize({ps})}}"


def table_paired_arms() -> None:
    """Every arm pair of the main crossover run, per dataset and label fraction.

    The arms of one run share graph, split and seeds, so the tests are paired by seed."""
    rows = []
    for ds, label, second in _PAIRED_ROWS:
        res = _load(_result(ds, "temporal_crossover.json"))
        levels = sorted(res["A_features"].keys(), key=float, reverse=True)
        for i, lv in enumerate(levels):
            blocks = {a: res[k][lv] for a, k in _ARM_KEYS.items()}
            if second:
                blocks = {a: _second_half(b) for a, b in blocks.items()}
            cells = " & ".join(_fmt_gap_p(_pair_test(blocks[a], blocks[b])) for a, b in _PAIRS)
            rows.append(f"{label if i == 0 else ''} & {float(lv):g} & {cells} \\\\")
        rows.append("\\addlinespace[2pt]")
    rows.pop()
    header = " & ".join(f"{a}$-${b}" for a, b in _PAIRS)
    body = ("% auto-generated -- paired arm tests of the main crossover run: gap in AP points (p)\n"
            f"\\begin{{tabular}}{{lc{'c' * len(_PAIRS)}}}\n\\toprule\n"
            f"Dataset & Frac. & {header} \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\bottomrule\n\\end{tabular}\n")
    _write("tab_paired_arms.tex", body)


