def table_selection() -> None:
    """Selection study: AP and cell purity across the lambda sweep (tab_selection.tex).

    lambda > 0 comes from method_results.json (fixed pool, lambda varies); lambda = 0 is
    the label-carving run of the generation ablation (ablation_results.json).
    """
    def _by_lambda(res: dict) -> Dict[float, dict]:
        """Blocks by lambda from the 'label|lam<lambda>' keys (the selection study's pool)."""
        out: Dict[float, dict] = {}
        for k, v in res.items():
            m = re.fullmatch(r"label\|lam([0-9.eE+-]+)", k)
            if m:
                out[float(m.group(1))] = v
        return out

    per_ds: Dict[str, Dict[float, dict]] = {}
    for ds in DATASETS:
        per_ds[ds] = _by_lambda(_load(_result(ds, "method_results.json")))
        per_ds[ds][0.0] = _load(_result(ds, "ablation_results.json"))["label|lam0"]
    lams = sorted({lam for d in per_ds.values() for lam in d})

    def block(metric: str, title: str) -> List[str]:
        out = [f"\\multicolumn{{{len(DATASETS)+1}}}{{l}}{{\\emph{{{title}}}}} \\\\"]
        for lam in lams:
            cells = " & ".join(_ms(per_ds[ds][lam], metric) for ds in DATASETS)
            out.append(f"${lam:g}$ & {cells} \\\\")
        return out

    header = " & ".join(PRETTY[d] for d in DATASETS)
    lines = block("ap", "Average Precision") + ["\\midrule"] + \
        block("sel_fraud_purity", "Gate-weighted fraud purity of the cells")
    body = (
        "% auto-generated by 09_make_tables.py -- selection study, AP + selected-cell\n"
        "% purity across the lambda sweep, 5 seeds (candidate pool fixed)\n"
        f"\\begin{{tabular}}{{l{'c'*len(DATASETS)}}}\n\\toprule\n"
        f"$\\lambda$ & {header} \\\\\n\\midrule\n" + "\n".join(lines) +
        "\n\\bottomrule\n\\end{tabular}\n"
    )
    _write("tab_selection.tex", body)


