def _result(ds: str, name: str) -> Path:
    """results/<ds>/<name>."""
    return config.RESULTS / ds / name


def _result_glob(ds: str, pattern: str) -> List[Path]:
    """Files in results/<ds>/ matching pattern."""
    return sorted((config.RESULTS / ds).glob(pattern))


def _load(path: Path) -> dict:
    """Load a result JSON."""
    return json.loads(path.read_text())


def _ms(d: dict, metric: str) -> str:
    """mean±std of a metric block."""
    m = d[metric]
    return f"{m['mean']:.3f}\\,$\\pm$\\,{m['std']:.3f}"


def _write(name: str, body: str) -> None:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    (TABLES_DIR / name).write_text(body)
    log.info("wrote %s", TABLES_DIR / name)


